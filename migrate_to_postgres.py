import os
import sqlite3
from pathlib import Path

import psycopg
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent
load_dotenv(dotenv_path=BASE_DIR / ".env")

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is missing from .env")

SQLITE_PATH = BASE_DIR / "readings.sqlite3"

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_salt TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_premium BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES users(id),
    participant_id TEXT NOT NULL,
    device_id TEXT NOT NULL,
    captured_at TEXT NOT NULL,
    acceleration_m_s2_x DOUBLE PRECISION NOT NULL,
    acceleration_m_s2_y DOUBLE PRECISION NOT NULL,
    acceleration_m_s2_z DOUBLE PRECISION NOT NULL,
    angular_velocity_rad_s_x DOUBLE PRECISION NOT NULL,
    angular_velocity_rad_s_y DOUBLE PRECISION NOT NULL,
    angular_velocity_rad_s_z DOUBLE PRECISION NOT NULL,
    heart_rate_bpm DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_expires_at
ON sessions (expires_at);

CREATE INDEX IF NOT EXISTS idx_readings_captured_at
ON readings (captured_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_readings_owner_participant_captured
ON readings (owner_user_id, participant_id, captured_at DESC, id DESC);
"""


def main():
    if not SQLITE_PATH.exists():
        raise FileNotFoundError("SQLite database readings.sqlite3 was not found")

    source = sqlite3.connect(SQLITE_PATH)
    source.row_factory = sqlite3.Row

    try:
        with psycopg.connect(DATABASE_URL) as target:
            with target.cursor() as cursor:
                cursor.execute(SCHEMA)

                tables = {
                    "users": (
                        "id, email, password_salt, password_hash, created_at, "
                        "role, is_active, is_premium"
                    ),
                    "readings": (
                        "id, owner_user_id, participant_id, device_id, captured_at, "
                        "acceleration_m_s2_x, acceleration_m_s2_y, acceleration_m_s2_z, "
                        "angular_velocity_rad_s_x, angular_velocity_rad_s_y, "
                        "angular_velocity_rad_s_z, heart_rate_bpm"
                    ),
                    "sessions": "token_hash, user_id, expires_at",
                    "admin_audit": "id, actor_user_id, action, target, created_at",
                }

                for table, columns in tables.items():
                    names = [name.strip() for name in columns.split(",")]
                    rows = source.execute(
                        f"SELECT {columns} FROM {table}"
                    ).fetchall()

                    values = []
                    for row in rows:
                        record = [row[name] for name in names]

                        if table == "users":
                            record[names.index("is_active")] = bool(
                                record[names.index("is_active")]
                            )
                            record[names.index("is_premium")] = bool(
                                record[names.index("is_premium")]
                            )

                        values.append(tuple(record))

                    if values:
                        placeholders = ", ".join(["%s"] * len(names))
                        cursor.executemany(
                            f"""
                            INSERT INTO {table} ({columns})
                            VALUES ({placeholders})
                            ON CONFLICT DO NOTHING
                            """,
                            values,
                        )

                    print(f"Copied {len(values)} source records from {table}")

                for table in ("users", "readings", "admin_audit"):
                    cursor.execute(
                        f"""
                        SELECT setval(
                            pg_get_serial_sequence('{table}', 'id'),
                            COALESCE((SELECT MAX(id) FROM {table}), 1),
                            EXISTS (SELECT 1 FROM {table})
                        )
                        """
                    )

                print("\nNeon database record counts:")
                for table in tables:
                    cursor.execute(f"SELECT COUNT(*) FROM {table}")
                    print(f"{table}: {cursor.fetchone()[0]} records")

        print("\nMigration completed successfully.")

    finally:
        source.close()


if __name__ == "__main__":
    main()
